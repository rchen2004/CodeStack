import { ObjectId } from 'mongodb';
import BookmarkModel from '../models/bookmark.model';
import CollectionModel from '../models/collection.model';
import NotificationModel from '../models/notification.model';
import emitNotification from '../utils/realtime';

import type {
  PopulatedDatabaseQuestion,
  PopulatedDatabaseAnswer,
  NotificationLocation,
  DatabaseUser,
  DatabaseNotification,
  DatabaseMessage,
  DatabaseChat,
} from '../types/types';
import UserModel from '../models/users.model';

/**
 * Shape for new notification documents inserted into MongoDB.
 * _id is generated by MongoDB.
 */
type NewNotificationDoc = Omit<DatabaseNotification, '_id'>;

/**
 * Resolve a NotificationLocation string from flags.
 */
function resolveLocation(flags: {
  inCollection: boolean;
  inCommunity: boolean;
}): NotificationLocation {
  if (flags.inCollection && flags.inCommunity) return 'collection/community';
  if (flags.inCollection) return 'collection';
  return 'community';
}

/**
 * Human-readable phrase for where the activity happened.
 *
 * If the question has a populated community with a name, we always say:
 *   the "<name>" community
 *
 * Otherwise we fall back to a generic phrase that includes the location slug
 * (e.g., "your collection").
 */
function describeQuestionLocation(
  location: NotificationLocation,
  question: PopulatedDatabaseQuestion,
): string {
  const communityName = question.community?.name;

  // Prefer explicit community name whenever we have it
  if (communityName && communityName.trim().length > 0) {
    return `the "${communityName}" community`;
  }

  // Fallback: generic wording by location
  if (location === 'collection') return 'your collection';
  if (location === 'collection/community') return 'your collection and community';

  // Default
  return `your ${location}`;
}

/**
 * Internal helper: find all users who should be notified about activity on this question,
 * and track whether they see it via collections and/or communities.
 */
async function computeRecipientsForQuestion(
  question: PopulatedDatabaseQuestion,
): Promise<Map<string, NotificationLocation>> {
  const questionId = question._id as ObjectId;

  // 1. Collections that contain this question
  const collections = await CollectionModel.find({ questions: questionId }).select('_id').exec();
  const collectionIds = collections.map(c => c._id);

  // 2. Bookmarks on those collections and the community (if any)
  const [collectionBookmarks, communityBookmarks] = await Promise.all([
    collectionIds.length
      ? BookmarkModel.find({
          targetType: 'Collection',
          targetId: { $in: collectionIds },
        }).exec()
      : Promise.resolve([]),
    question.community?._id
      ? BookmarkModel.find({
          targetType: 'Community',
          targetId: question.community._id,
        }).exec()
      : Promise.resolve([]),
  ]);

  // 🔒 If the community is PRIVATE, only participants who bookmarked it get notifications.
  let filteredCommunityBookmarks = communityBookmarks;
  const communityVisibility = question.community?.visibility;
  const communityParticipants = (question.community?.participants ?? []).filter(
    (p): p is string => typeof p === 'string',
  );

  if (communityVisibility === 'PRIVATE' && communityParticipants.length > 0) {
    const participantSet = new Set(communityParticipants);
    filteredCommunityBookmarks = communityBookmarks.filter(b => participantSet.has(b.username));
  }

  // 3. Merge into username -> flags
  const byUser = new Map<string, { inCollection: boolean; inCommunity: boolean }>();

  const ensureEntry = (username: string) => {
    if (!byUser.has(username)) {
      byUser.set(username, { inCollection: false, inCommunity: false });
    }
    return byUser.get(username)!;
  };

  for (const b of collectionBookmarks) {
    const entry = ensureEntry(b.username);
    entry.inCollection = true;
  }

  // ⬇️ Use filteredCommunityBookmarks here
  for (const b of filteredCommunityBookmarks) {
    const entry = ensureEntry(b.username);
    entry.inCommunity = true;
  }

  // 4. Convert flags → NotificationLocation
  const result = new Map<string, NotificationLocation>();
  for (const [username, flags] of byUser.entries()) {
    result.set(username, resolveLocation(flags));
  }

  return result;
}

/**
 * Returns the list of usernames who follow the given actor username.
 */
async function getFollowerUsernamesForActor(actorUsername: string): Promise<string[]> {
  // Find the actor so we know their _id
  const actor = (await UserModel.findOne({ username: actorUsername })
    .select('_id')
    .exec()) as DatabaseUser | null;

  if (!actor) {
    return [];
  }

  // All users whose "following" array contains actor._id are followers
  const followers = (await UserModel.find({ following: actor._id })
    .select('username')
    .exec()) as Pick<DatabaseUser, 'username'>[];

  return followers.map(u => u.username).filter((name): name is string => Boolean(name));
}

/**
 * Fan-out for a newly created question.
 * Persists notifications + pings via realtime util.
 */
export async function notifyOnNewQuestion(question: PopulatedDatabaseQuestion): Promise<void> {
  // Bookmark / community recipients
  const recipients = await computeRecipientsForQuestion(question);
  const questionId = question._id as ObjectId;

  const docs: NewNotificationDoc[] = [];

  // Persist notifications only for bookmark-based recipients
  if (recipients.size) {
    for (const [username, location] of recipients.entries()) {
      const locationPhrase = describeQuestionLocation(location, question);

      docs.push({
        user: username,
        actor: question.askedBy,
        message: `${question.askedBy} posted a question "${question.title}" in ${locationPhrase}`,
        eventDate: question.askDateTime,
        targetId: questionId,
        targetType: 'Question',
        location,
        link: `/question/${questionId.toString()}`,
        category: 'question',
        isRead: false,
      });
    }

    if (docs.length) {
      await NotificationModel.insertMany(docs);
    }
  }

  // Followers also receive real-time pings, even if they have no bookmarks
  const followerUsernames = await getFollowerUsernamesForActor(question.askedBy);

  const allRecipients = new Set<string>([
    ...recipients.keys(), // bookmark-based
    ...followerUsernames, // social followers
  ]);

  if (!allRecipients.size) {
    return;
  }

  for (const username of allRecipients) {
    emitNotification(username);
  }
}

/**
 * Fan-out for a newly created answer.
 */
export async function notifyOnNewAnswer(
  question: PopulatedDatabaseQuestion,
  answer: PopulatedDatabaseAnswer,
): Promise<void> {
  const recipients = await computeRecipientsForQuestion(question);
  const questionId = question._id as ObjectId;

  const docs: NewNotificationDoc[] = [];

  if (recipients.size) {
    for (const [username, location] of recipients.entries()) {
      const locationPhrase = describeQuestionLocation(location, question);

      docs.push({
        user: username,
        actor: answer.ansBy,
        message: `${answer.ansBy} posted an answer to "${question.title}" in ${locationPhrase}`,
        eventDate: answer.ansDateTime,
        targetId: questionId,
        targetType: 'Answer',
        location,
        link: `/question/${questionId.toString()}`,
        category: 'answer',
        isRead: false,
      });
    }

    if (docs.length) {
      await NotificationModel.insertMany(docs);
    }
  }

  // Followers of the answer author get real-time pings as well
  const followerUsernames = await getFollowerUsernamesForActor(answer.ansBy);

  const allRecipients = new Set<string>([...recipients.keys(), ...followerUsernames]);

  if (!allRecipients.size) {
    return;
  }

  for (const username of allRecipients) {
    emitNotification(username);
  }
}

export async function notifyOnDirectMessage(
  message: DatabaseMessage,
  chat: DatabaseChat,
): Promise<void> {
  // Only care about direct messages
  if (message.type !== 'direct') {
    return;
  }

  const rawText = (message.msg ?? '').toString().trim();
  const snippet =
    rawText.length === 0
      ? '(no message text)'
      : rawText.length > 140
        ? `${rawText.slice(0, 137)}…`
        : rawText;

  const eventDate = message.msgDateTime ?? new Date();

  const participants = chat.participants ?? [];

  // participants are usernames; filter out the sender
  const recipientUsernames = participants.filter(
    uname => typeof uname === 'string' && uname !== message.msgFrom,
  );

  if (!recipientUsernames.length) {
    return;
  }

  const baseDoc: Omit<DatabaseNotification, '_id'> = {
    user: '', // filled per-recipient below
    actor: message.msgFrom,
    message: `${message.msgFrom} sent you a message: "${snippet}"`,
    eventDate,
    targetId: message._id,
    targetType: 'User',
    location: 'direct',
    link: '/messaging/direct-message', // or your actual chat route
    category: 'direct',
    isRead: false,
  };

  const docs: Omit<DatabaseNotification, '_id'>[] = recipientUsernames.map(username => ({
    ...baseDoc,
    user: username,
  }));

  await NotificationModel.insertMany(docs);

  for (const username of recipientUsernames) {
    emitNotification(username);
  }
}
